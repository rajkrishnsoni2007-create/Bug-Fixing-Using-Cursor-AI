SUBJECT_COUNT = 3

students = [
    ["Rahul", 78, 88, 92],
    ["Priya", 65, 71, 69],
    ["Amit", 90, 94, 85],
    ["Sneha", 55, 60, 58],
    ["Vikram", 82, 79, 88]
]


def calculate_total(student_row):
    """Sum numeric scores in a student row, skipping the name."""
    total = 0
    for index in range(1, len(student_row)):
        total = total + student_row[index]
    return total


def calculate_average(total):
    return total / SUBJECT_COUNT


print("REPORT")

for student in students:
    total = calculate_total(student)
    average = calculate_average(total)

    if average >= 90:
        grade = "A"
    elif average >= 80:
        grade = "B"
    elif average >= 70:
        grade = "C"
    elif average >= 60:
        grade = "D"
    else:
        grade = "F"

    print(f"{student[0]}{total}{average}{grade}")

sum_of_averages = 0

for student in students:
    total = calculate_total(student)
    average = calculate_average(total)
    sum_of_averages = sum_of_averages + average

print(f"Class average:{sum_of_averages / len(students)}")

highest_average = 0
topper_name = ""

for student in students:
    total = calculate_total(student)
    average = calculate_average(total)

    if average > highest_average:
        highest_average = average
        topper_name = student[0]

print(f"Topper:{topper_name}{highest_average}")
